package com.taiyoudev.countdownnotification

import android.Manifest
import android.annotation.SuppressLint
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.content.Context
import android.content.pm.PackageManager
import android.os.Build
import androidx.core.app.NotificationCompat
import androidx.core.app.NotificationManagerCompat
import androidx.core.content.ContextCompat
import expo.modules.kotlin.modules.Module
import expo.modules.kotlin.modules.ModuleDefinition

private const val CHANNEL_ID = "rest-countdown"
private const val NOTIFICATION_ID = 7310

/**
 * Ongoing, silent notification showing a countdown that Android itself keeps up to date
 * (Notification chronometer), so the remaining rest time is visible outside the app without
 * any JavaScript running. It removes itself when the countdown ends.
 */
class CountdownNotificationModule : Module() {
  private val context: Context
    get() = appContext.reactContext ?: throw IllegalStateException("React context is not available")

  override fun definition() = ModuleDefinition {
    Name("CountdownNotification")

    Function("show") { title: String, body: String, endsAtMs: Double ->
      show(title, body, endsAtMs.toLong())
    }

    Function("dismiss") {
      NotificationManagerCompat.from(context).cancel(NOTIFICATION_ID)
    }
  }

  @SuppressLint("MissingPermission") // checked by canNotify()
  private fun show(title: String, body: String, endsAt: Long) {
    val manager = NotificationManagerCompat.from(context)
    val remaining = endsAt - System.currentTimeMillis()
    if (remaining <= 0 || !canNotify()) {
      manager.cancel(NOTIFICATION_ID)
      return
    }
    ensureChannel()

    val notification = NotificationCompat.Builder(context, CHANNEL_ID)
      .setSmallIcon(smallIcon())
      .setContentTitle(title)
      .setContentText(body)
      .setWhen(endsAt)
      .setShowWhen(true)
      .setUsesChronometer(true)
      .setChronometerCountDown(true)
      .setTimeoutAfter(remaining)
      .setOngoing(true)
      .setOnlyAlertOnce(true)
      .setSilent(true)
      .setCategory(NotificationCompat.CATEGORY_STOPWATCH)
      .setPriority(NotificationCompat.PRIORITY_LOW)
      .setContentIntent(openAppIntent())
      .build()

    manager.notify(NOTIFICATION_ID, notification)
  }

  private fun canNotify(): Boolean {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.TIRAMISU) return true
    return ContextCompat.checkSelfPermission(context, Manifest.permission.POST_NOTIFICATIONS) ==
      PackageManager.PERMISSION_GRANTED
  }

  private fun ensureChannel() {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) return
    val manager = context.getSystemService(NotificationManager::class.java)
    if (manager.getNotificationChannel(CHANNEL_ID) != null) return
    val channel = NotificationChannel(CHANNEL_ID, "Décompte du repos", NotificationManager.IMPORTANCE_LOW).apply {
      description = "Temps de repos restant, affiché pendant la séance"
      setShowBadge(false)
      enableVibration(false)
      setSound(null, null)
    }
    manager.createNotificationChannel(channel)
  }

  /** Icon generated by the expo-notifications config plugin, else the app icon. */
  private fun smallIcon(): Int {
    val generated = context.resources.getIdentifier("notification_icon", "drawable", context.packageName)
    return if (generated != 0) generated else context.applicationInfo.icon
  }

  private fun openAppIntent(): PendingIntent? {
    val intent = context.packageManager.getLaunchIntentForPackage(context.packageName) ?: return null
    return PendingIntent.getActivity(
      context,
      0,
      intent,
      PendingIntent.FLAG_IMMUTABLE or PendingIntent.FLAG_UPDATE_CURRENT,
    )
  }
}
